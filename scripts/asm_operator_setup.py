#!/usr/bin/env python3
"""Generate the ASM operator key and TOTP secret. Prints both exactly once.

Operator mode is disabled unless ASM_OPERATOR_KEY_HASH and ASM_OPERATOR_TOTP_SECRET
are set in .env. This script makes a high-entropy key and a TOTP secret, shows them
once (the key and the TOTP secret are never recoverable afterward), and stores only
the bcrypt hash of the key and the TOTP secret. Add the two printed lines to your
.env, or pass --write <path> to append them, then restart the service.

Run it on the box, as a human, not from an automated deploy. No em dashes here.
"""
import argparse
import pathlib
import secrets
import sys

_ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(_ROOT))

import pyotp  # noqa: E402

from app.asm import operator  # noqa: E402


def main() -> int:
    ap = argparse.ArgumentParser(description="Generate ASM operator credentials.")
    ap.add_argument("--write", metavar="ENV_PATH",
                    help="append the two lines to this .env file instead of only printing them")
    ap.add_argument("--issuer", default="FalconEye ASM")
    ap.add_argument("--account", default="operator")
    args = ap.parse_args()

    key = secrets.token_urlsafe(32)
    totp_secret = pyotp.random_base32()
    key_hash = operator.hash_key(key)
    uri = pyotp.TOTP(totp_secret).provisioning_uri(name=args.account, issuer_name=args.issuer)

    env_lines = [f"ASM_OPERATOR_KEY_HASH={key_hash}", f"ASM_OPERATOR_TOTP_SECRET={totp_secret}"]

    print("=" * 70)
    print("FalconEye operator credentials. Shown ONCE. Store the key in a password")
    print("manager and the TOTP secret in an authenticator app now.")
    print("=" * 70)
    print(f"\nOperator key (you type this at unlock):\n    {key}\n")
    print(f"TOTP secret (add to your authenticator):\n    {totp_secret}\n")
    print(f"Or scan this provisioning URI:\n    {uri}\n")
    print("Add these two lines to /opt/falconeye/.env (the key hash and the secret,")
    print("never the key itself), then restart the service:\n")
    for line in env_lines:
        print(f"    {line}")
    print()

    if args.write:
        path = pathlib.Path(args.write).expanduser()
        existing = path.read_text(encoding="utf-8") if path.exists() else ""
        if "ASM_OPERATOR_KEY_HASH=" in existing or "ASM_OPERATOR_TOTP_SECRET=" in existing:
            print(f"Refusing to write: {path} already has operator lines. Edit it by hand.")
            return 1
        with path.open("a", encoding="utf-8") as fh:
            fh.write("\n# ----- ASM operator mode (generated by asm_operator_setup.py) -----\n")
            fh.write("\n".join(env_lines) + "\n")
        print(f"Appended the two lines to {path}. Restart the service to activate.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
